"""Generalized dynamics on Min(1,3) x SU(N).

The evolution parameter is the lab-frame coordinate time t = x^0 (in km), so a
dot denotes d/dt. The coupled system integrated here is

    dx^mu/dt   = u^mu / u^0
    du^mu/dt   = (1/(m u^0)) [ g I^a F^{a mu nu} u_nu  +  Q^mu_topological ]
    d|psi>/dt  = -i [ H_flavor(x) + g A^a_mu (dx^mu/dt) T_a ] |psi>
    I^a        = <psi| T_a |psi>

The first bracket is the non-Abelian Lorentz force (Q_gauge); the second is
the steering force generated by gradients of the MSW potential,

    M(x) = m + kappa <psi| H_matter |psi>,   M du^mu/dtau = (eta^{mu nu} - u^mu u^nu) d_nu M,

i.e. the matter potential acts as a refractive index for the wave packet. That
form is orthogonal to u^mu by construction, so the mass shell u.u = 1 holds
exactly, and it conserves the refractive energy M u^0 for a static profile. Taking d/dt of I^a = <psi|T_a|psi> reproduces the internal precession
law dI^a/dt = g f^{abc} A^b_mu (dx^mu/dt) I^c whenever H_flavor is switched
off; with H_flavor on, the extra "flavor torque" is measured by `verify`.
"""

from __future__ import annotations

from dataclasses import dataclass, field

import numpy as np

from .algebra import color_charge, generators, structure_constants
from .physics import METRIC, FlavorHamiltonian, GaugeField, MatterProfile


@dataclass
class RobotState:
    x: np.ndarray  # 4-position (t, x, y, z), km
    u: np.ndarray  # 4-velocity, dimensionless, u.u = 1
    psi: np.ndarray  # internal SU(N) state

    def copy(self) -> RobotState:
        return RobotState(self.x.copy(), self.u.copy(), self.psi.copy())


@dataclass
class Trajectory:
    t: np.ndarray
    x: np.ndarray  # (steps, 4)
    u: np.ndarray  # (steps, 4)
    psi: np.ndarray  # (steps, N) complex
    charge: np.ndarray  # (steps, N^2-1)
    probs: np.ndarray  # (steps, N)
    rho: np.ndarray  # matter density along the path
    potential: np.ndarray  # V(x) in km^-1
    norm: np.ndarray  # <psi|psi>
    energy: np.ndarray  # refractive energy M(x) u^0
    f_gauge: np.ndarray  # |Q_gauge| along the path, km^-2
    f_top: np.ndarray  # |Q_topological| along the path, km^-2
    mass_shell: np.ndarray  # u.u
    casimir: np.ndarray  # sum_a (I^a)^2
    meta: dict = field(default_factory=dict)

    @property
    def path_length(self) -> np.ndarray:
        d = np.diff(self.x[:, 1:], axis=0)
        return np.concatenate([[0.0], np.cumsum(np.linalg.norm(d, axis=1))])


def normalize_four_velocity(u: np.ndarray) -> np.ndarray:
    """Rescale the spatial part so that u.u = +1 with signature (+,-,-,-)."""
    spatial = np.linalg.norm(u[1:])
    return np.array([np.sqrt(1.0 + spatial**2), *u[1:]])


def boosted_state(
    beta: np.ndarray, psi0: np.ndarray, x0: np.ndarray | None = None
) -> RobotState:
    """Build a state from a 3-velocity beta (units of c) and an internal state."""
    beta = np.asarray(beta, dtype=float)
    b2 = float(beta @ beta)
    if b2 >= 1.0:
        raise ValueError("|beta| must be < 1")
    gamma = 1.0 / np.sqrt(1.0 - b2)
    u = np.array([gamma, *(gamma * beta)])
    psi = np.asarray(psi0, dtype=complex)
    psi = psi / np.linalg.norm(psi)
    return RobotState(np.zeros(4) if x0 is None else np.asarray(x0, float), u, psi)


class QSE3Dynamics:
    """Integrator for the coupled spacetime / internal-state system."""

    def __init__(
        self,
        hamiltonian: FlavorHamiltonian,
        matter: MatterProfile,
        gauge: GaugeField,
        mass_km_inv: float = 1.0e-3,
        topological_gain: float = 1.0,
        wong_only: bool = False,
    ) -> None:
        self.h = hamiltonian
        self.matter = matter
        self.gauge = gauge
        self.mass = mass_km_inv
        self.topological_gain = topological_gain
        self.wong_only = wong_only  # switch off H_flavor to isolate Wong precession
        self.n = hamiltonian.n
        self.t_gen = generators(self.n)
        self.f_abc = structure_constants(self.n)
        self._matter_op = np.zeros((self.n, self.n), dtype=complex)
        self._matter_op[0, 0] = 1.0

    # -- right-hand side ---------------------------------------------------

    def effective_mass(self, x: np.ndarray, psi: np.ndarray) -> float:
        """M(x) = m + kappa <psi|H_matter|psi>: matter as a refractive index."""
        if self.topological_gain == 0.0:
            return self.mass
        weight = float(np.real(np.vdot(psi, self._matter_op @ psi)))
        return self.mass + self.topological_gain * weight * self.matter.potential(x)

    def force_split(self, s: RobotState) -> tuple[float, float]:
        """Euclidean magnitudes of the two force sectors, for reporting."""
        charge = color_charge(s.psi)
        f_up = self.gauge.field_strength_upper(s.x)
        gauge = self.gauge.coupling * np.einsum(
            "mna,a,n->m", f_up, charge, METRIC @ s.u
        )
        top = np.zeros(4)
        if self.topological_gain != 0.0:
            weight = float(np.real(np.vdot(s.psi, self._matter_op @ s.psi)))
            grad_low = self.topological_gain * weight * self.matter.grad_potential(s.x)
            top = (METRIC @ grad_low) - s.u * float(s.u @ grad_low)
        return float(np.linalg.norm(gauge)), float(np.linalg.norm(top))

    def derivatives(self, s: RobotState) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
        u0 = s.u[0]
        xdot = s.u / u0  # dx^mu/dt, with xdot^0 = 1

        v = self.matter.potential(s.x)
        h_flavor = np.zeros((self.n, self.n), dtype=complex) if self.wong_only else self.h.total(v)
        h_gauge = self.gauge.connection_term(s.x, xdot)
        dpsi = -1j * (h_flavor + h_gauge) @ s.psi

        charge = color_charge(s.psi)

        # Q_gauge: non-Abelian Lorentz force  g I^a F^{a mu nu} u_nu
        f_up = self.gauge.field_strength_upper(s.x)  # (4,4,dim), indices up
        u_low = METRIC @ s.u
        force = self.gauge.coupling * np.einsum("mna,a,n->m", f_up, charge, u_low)

        # Q_topological: refraction off gradients of the matter-induced mass.
        # From S = -int M(x) dtau one gets d(M u^mu)/dtau = d^mu M, i.e.
        #     M du^mu/dtau = (eta^{mu nu} - u^mu u^nu) d_nu M,
        # which is automatically orthogonal to u (the mass shell is preserved
        # exactly) and conserves the refractive energy M u^0 for a static
        # profile. Using a plain constant mass here instead produces a genuine
        # runaway once |u^y| approaches gamma.
        mass_eff = self.mass
        if self.topological_gain != 0.0:
            weight = float(np.real(np.vdot(s.psi, self._matter_op @ s.psi)))
            mass_eff = self.mass + self.topological_gain * weight * v
            grad_low = self.topological_gain * weight * self.matter.grad_potential(s.x)
            force = force + (METRIC @ grad_low) - s.u * float(s.u @ grad_low)

        du = force / (mass_eff * u0)
        return xdot, du, dpsi

    # -- integration -------------------------------------------------------

    def step(self, s: RobotState, dt: float) -> RobotState:
        """Classical RK4 on (x, u, psi), followed by a unitarity re-projection."""

        def rhs(state: RobotState):
            return self.derivatives(state)

        def shift(base: RobotState, k, h) -> RobotState:
            return RobotState(base.x + h * k[0], base.u + h * k[1], base.psi + h * k[2])

        k1 = rhs(s)
        k2 = rhs(shift(s, k1, dt / 2))
        k3 = rhs(shift(s, k2, dt / 2))
        k4 = rhs(shift(s, k3, dt))

        x = s.x + dt / 6 * (k1[0] + 2 * k2[0] + 2 * k3[0] + k4[0])
        u = s.u + dt / 6 * (k1[1] + 2 * k2[1] + 2 * k3[1] + k4[1])
        psi = s.psi + dt / 6 * (k1[2] + 2 * k2[2] + 2 * k3[2] + k4[2])

        u = normalize_four_velocity(u)
        psi = psi / np.linalg.norm(psi)
        return RobotState(x, u, psi)

    def run(self, s0: RobotState, t_final_km: float, steps: int = 2000) -> Trajectory:
        dt = t_final_km / steps
        s = s0.copy()
        s.u = normalize_four_velocity(s.u)
        s.psi = s.psi / np.linalg.norm(s.psi)

        rec_x, rec_u, rec_psi, rec_q = [], [], [], []
        rec_rho, rec_v, rec_e = [], [], []
        rec_fg, rec_ft = [], []

        for _ in range(steps + 1):
            rec_x.append(s.x.copy())
            rec_u.append(s.u.copy())
            rec_psi.append(s.psi.copy())
            rec_q.append(color_charge(s.psi))
            rec_rho.append(self.matter.rho(s.x))
            rec_v.append(self.matter.potential(s.x))
            rec_e.append(self.effective_mass(s.x, s.psi) * s.u[0])
            fg, ft = self.force_split(s)
            rec_fg.append(fg)
            rec_ft.append(ft)
            s = self.step(s, dt)

        x = np.array(rec_x)
        u = np.array(rec_u)
        psi = np.array(rec_psi)
        charge = np.array(rec_q)
        return Trajectory(
            t=x[:, 0],
            x=x,
            u=u,
            psi=psi,
            charge=charge,
            probs=np.abs(psi) ** 2,
            rho=np.array(rec_rho),
            potential=np.array(rec_v),
            norm=np.sum(np.abs(psi) ** 2, axis=1),
            energy=np.array(rec_e),
            f_gauge=np.array(rec_fg),
            f_top=np.array(rec_ft),
            mass_shell=np.einsum("ij,sj,si->s", METRIC, u, u),
            casimir=np.sum(charge**2, axis=1),
            meta={
                "gauge": self.gauge.name,
                "matter": self.matter.name,
                "energy_gev": self.h.energy_gev,
                "mass_km_inv": self.mass,
                "wong_only": self.wong_only,
                "steps": steps,
                "dt_km": dt,
            },
        )

    # -- independent check of the precession law ---------------------------

    def wong_precession(self, traj: Trajectory) -> np.ndarray:
        """Integrate dI^a/dt = g f^{abc} A^b_mu xdot^mu I^c on its own.

        Compared against <psi|T_a|psi> from the full run, this isolates how
        much of the internal motion is driven purely by the gauge connection
        and how much comes from the flavor Hamiltonian.
        """
        dt = traj.meta["dt_km"]
        charge = np.zeros_like(traj.charge)
        charge[0] = traj.charge[0]
        g = self.gauge.coupling

        def deriv(i: int, iv: np.ndarray) -> np.ndarray:
            xdot = traj.u[i] / traj.u[i, 0]
            a = self.gauge.a_mu(traj.x[i])
            a_dot = np.einsum("m,ma->a", xdot, a)
            return g * np.einsum("abc,b,c->a", self.f_abc, a_dot, iv)

        for i in range(len(traj.t) - 1):
            k1 = deriv(i, charge[i])
            k2 = deriv(i, charge[i] + dt / 2 * k1)
            k3 = deriv(i, charge[i] + dt / 2 * k2)
            k4 = deriv(i + 1, charge[i] + dt * k3)
            charge[i + 1] = charge[i] + dt / 6 * (k1 + 2 * k2 + 2 * k3 + k4)
        return charge
