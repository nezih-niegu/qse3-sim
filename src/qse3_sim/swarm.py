@dataclass
class SwarmTrajectory:
    t: np.ndarray  # (T,)
    x: np.ndarray  # (T, R, 4)
    u: np.ndarray  # (T, R, 4)
    s: np.ndarray  # (T, R, 3) guidance oscillators
    ref: np.ndarray  # (T, 3) global reference position, km
    p_star: np.ndarray  # (T, R, 3) guidance slots, km
    offsets: np.ndarray  # (R, 3)
    d_star: np.ndarray  # (R, R)
    length_scale: float
    charge: np.ndarray  # (T, R, N^2-1) reduced color charge
    probs: np.ndarray  # (T, R, N) flavor occupation from rho_r
    entropy: np.ndarray  # (T, R) von Neumann entropy of rho_r, bits
    eta: np.ndarray  # (T, R) actuation efficiency |I_r| / |I|_pure
    throttle: np.ndarray  # (T,) entangler throttle actually applied
    norm: np.ndarray  # (T,) <Psi|Psi>
    mass_shell: np.ndarray  # (T, R) u.u
    accel_cmd: np.ndarray  # (T, R) |commanded coordinate acceleration|
    saturated: np.ndarray  # (T, R) bool
    lyapunov_fn: np.ndarray  # (T, R) V_r = 1/2 (omega^2 |e|^2 + |edot|^2)
    lyap_t: np.ndarray  # (K,) window end times
    lyap_guidance: np.ndarray  # (K, R) local conditional exponent of each oscillator
    lyap_reference: np.ndarray  # (K,) local exponent of the free reference flow
    lyap_mechanical: np.ndarray  # (K, R) Benettin twins, empty if not run
    lyap_guidance_pred: np.ndarray = field(default_factory=lambda: np.zeros((0, 0)))  # (K, R)
    purity: np.ndarray = field(default_factory=lambda: np.zeros((0, 0)))  # (T, R) Tr rho_r^2
    accel_mean: np.ndarray = field(default_factory=lambda: np.zeros((0, 0)))  # (T, R) km^-1
    accel_spread: np.ndarray = field(default_factory=lambda: np.zeros((0, 0)))  # (T, R) km^-1
    accel_phys: np.ndarray = field(default_factory=lambda: np.zeros((0, 0, 3)))  # (T, R, 3)
    accel_ctrl: np.ndarray = field(default_factory=lambda: np.zeros((0, 0, 3)))  # (T, R, 3)
    meta: dict = field(default_factory=dict)

    @property
    def n_robots(self) -> int:
        return self.x.shape[1]

    @property
    def pos(self) -> np.ndarray:
        return self.x[:, :, 1:]

    @property
    def tracking_error(self) -> np.ndarray:
        """(T, R, 3) mechanical error to the robot's own guidance slot."""
        return self.pos - self.p_star

    @property
    def sync_error(self) -> np.ndarray:
        """(T, R, 3) guidance desynchronization L (s_r - s_ref), km."""
        return self.p_star - self.offsets[None] - self.ref[:, None, :]

    @property
    def formation_error(self) -> np.ndarray:
        """(T, R, 3) total error to the design slot p_ref + delta_r."""
        return self.pos - (self.ref[:, None, :] + self.offsets[None])

    @property
    def distances(self) -> np.ndarray:
        d = self.pos[:, :, None, :] - self.pos[:, None, :, :]
        return np.linalg.norm(d, axis=3)

    @property
    def distance_error(self) -> np.ndarray:
        """(T,) worst relative deviation of any inter-robot distance from design."""
        r = self.n_robots
        if r < 2:
            return np.zeros(len(self.t))
        iu = np.triu_indices(r, 1)
        d = self.distances[:, iu[0], iu[1]]
        ds = self.d_star[iu]
        return np.max(np.abs(d - ds) / ds, axis=1)

    @property
    def distance_error_pairmean(self) -> np.ndarray:
        """(T,) relative distance error averaged over all pairs."""
        r = self.n_robots
        if r < 2:
            return np.zeros(len(self.t))
        iu = np.triu_indices(r, 1)
        d = self.distances[:, iu[0], iu[1]]
        ds = self.d_star[iu]
        return np.mean(np.abs(d - ds) / ds, axis=1)

    @property
    def guidance_lyapunov(self) -> np.ndarray:
        return self.lyap_guidance.mean(axis=0)

    @property
    def mechanical_lyapunov(self) -> np.ndarray:
        if self.lyap_mechanical.size == 0:
            return np.full(self.n_robots, np.nan)
        return self.lyap_mechanical.mean(axis=0)


def _apply_local(psi: np.ndarray, op: np.ndarray, axis: int) -> np.ndarray:
    return np.moveaxis(np.tensordot(op, psi, axes=([1], [axis])), 0, axis)


def reduced_density(psi: np.ndarray, axis: int) -> np.ndarray:
    m = np.moveaxis(psi, axis, 0).reshape(psi.shape[axis], -1)
    return m @ m.conj().T


def von_neumann_bits(rho: np.ndarray) -> float:
    w = np.linalg.eigvalsh(rho)
    w = w[w > 1e-14]
    return float(-np.sum(w * np.log2(w)))


def product_state(n: int, flavors: list[int]) -> np.ndarray:
    psi = np.array(1.0 + 0j)
    for f in flavors:
        v = np.zeros(n, dtype=complex)
        v[f % n] = 1.0
        psi = np.multiply.outer(psi, v)
    return psi


