"""An entangled swarm of R QSE(3) robots.

Each robot r carries its own worldline (x_r, u_r) on Min(1,3), but the internal
state is no longer a product of R separate SU(N) spinors. It is one joint
state in the tensor product

    H_swarm = C^N (x) C^N (x) ... (x) C^N        (R factors, dim N^R)

evolving under

    H = sum_r  H_r(x_r, xdot_r)  (x) 1_rest
      + sum_{r<s} w_rs(x, u) * sum_a T_a^(r) T_a^(s)

The single-robot pieces H_r = H_flavor(V(x_r)) + g A^a_mu(x_r) xdot_r^mu T_a are
exactly the ones in `dynamics.py`. The pair term is the SU(N) exchange
interaction; for the fundamental representation

    sum_a T_a (x) T_a = (1/2) SWAP - (1/2N) 1,

so it is a flavor swap between robots r and s. Its weight

    w_rs = K(|x_r - x_s|) * [ mu_ent + mu_nunu (1 - vhat_r . vhat_s) ]

has two parts: an engineered entangling channel mu_ent (the robots generate
entanglement on purpose) and the physical neutrino-neutrino forward-scattering
term, whose (1 - cos theta_rs) factor is the one from collective neutrino
oscillations. Both are cut off by the kernel K(r) = exp(-r / ell).

Why the kinematics change. A robot in an entangled swarm has no state vector of
its own, only a reduced density matrix rho_r = Tr_{others} |Psi><Psi|. Every
force that moved the single robot is built from its internal state, so each one
must now be read off rho_r:

    color charge     I^a_r = Tr(rho_r T_a)            (Wong force g I^a F^{a mu nu} u_nu)
    refractive mass  M_r   = m + kappa Tr(rho_r P_e) V  (Q_topological)

For a pure single robot |I| is pinned to sqrt((N-1)/2N). Entanglement shrinks
the Bloch vector, |I_r| < sqrt((N-1)/2N), so the same background field pushes an
entangled robot less, and a controller that steers through the charge loses
authority in proportion. The ratio

    eta_r = |I_r| / sqrt((N-1)/2N)  in [0, 1]

is the actuation efficiency, and it is what couples entanglement to motion.

Control. The swarm follows a global reference path generated by the Lorenz
flow (a chaotic exploration trajectory in the sense of chaotic mobile robots),
while holding a rigid formation. The law is a chaos-synchronization controller:
exact feed-forward of the reference flow plus linear error feedback, a
distance-rigidity term and velocity consensus. Formation is kept when every
robot's conditional Lyapunov exponent (the exponent of its own perturbations
with the reference held fixed) is negative, even though the reference itself
has a positive one. `robot_ftle` measures those exponents with Benettin twin
trajectories through the full entangled dynamics.
"""

