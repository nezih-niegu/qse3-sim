def simulate_guidance(
    guide: GuidanceNetwork,
    ref: LorenzReference,
    r: int,
    scatter_km: float,
    steps: int,
    seed: int = 0,
    floor_km: float = 1e-4,
) -> dict:
    """Integrate only the coupled Lorenz oscillators against the reference.

    The guidance layer does not depend on the mechanical or quantum state, so
    its synchronization can be studied at a fraction of the cost. Returns the
    time grid (km), the error L(s_r - s_ref) (T, R, 3) and its norm per robot
    (km), and the growth rate of the RMS desync (km^-1) fitted over its
    linear regime. The RMS mixes all network modes; the exact test of the
    synchronization proposition projects `error` onto the slowest eigenvector
    of the coupling matrix (see the paper experiments).
    """
    tt = ref.duration_km
    dt = tt / steps
    rng = np.random.default_rng(seed)
    s = np.tile(ref.s(0.0), (r, 1))
    kick = rng.normal(size=(r, 3))
    s += (scatter_km / ref.length_scale) * kick / np.linalg.norm(kick, axis=1, keepdims=True)
    ts, errs = [], []
    t = 0.0
    for k in range(steps + 1):
        ts.append(t)
        errs.append(ref.length_scale * (s - ref.s(t)[None]))
        if k == steps:
            break
        k1, _ = guide.rates(s, ref, t)
        k2, _ = guide.rates(s + dt / 2 * k1, ref, t + dt / 2)
        k3, _ = guide.rates(s + dt / 2 * k2, ref, t + dt / 2)
        k4, _ = guide.rates(s + dt * k3, ref, t + dt)
        s = s + dt / 6 * (k1 + 2 * k2 + 2 * k3 + k4)
        t += dt
    ts = np.array(ts)
    err = np.array(errs)  # (T, R, 3) km
    des = np.linalg.norm(err, axis=2)
    rms = np.sqrt(np.mean(des**2, axis=1))
    # Fit only where the error is linear and above the integrator's floor: RK4
    # against the reference's dense interpolant leaves a desync of ~1e-6 km,
    # and above ~0.5 km the Lorenz nonlinearity saturates growth.
    ok = (rms > floor_km) & (rms < 0.5) & (ts > 0.1 * tt)
    slope = float("nan")
    if ok.sum() >= 20:
        slope = float(np.polyfit(ts[ok], np.log(rms[ok]), 1)[0])
    return {"t": ts, "error": err, "desync": des, "rms": rms, "growth_rate": slope,
            "fit_points": int(ok.sum())}


def slowest_mode_check(guide: GuidanceNetwork, ref: LorenzReference, r: int, out: dict) -> dict:
    """Exact test of the synchronization proposition on a guidance run.

    With identity coupling the linearized error E(t) (R x 3) splits along the
    eigenvectors v_k of M = kappa_c L + kappa_p P, and each mode obeys
    a_k(t) = exp(-mu_k t) Phi(t) a_k(0), with Phi the tangent propagator of the
    free Lorenz flow along the reference. This projects the simulated error on
    the slowest eigenvector and integrates Phi(t) a(0) independently, so the two
    log-amplitudes can be compared point by point.
    """
    mu, vecs = np.linalg.eigh(guide.coupling_matrix(r))
    v = vecs[:, 0]
    ts = out["t"]
    a = np.einsum("r,trk->tk", v, out["error"])
    prm, tt = ref.params, ref.time_scale
    phi = a[0].copy()
    pred = [phi.copy()]
    for k in range(len(ts) - 1):
        t0, h = ts[k], ts[k + 1] - ts[k]

        def f(w, tau):
            return lorenz_jacobian(ref.s(tau), *prm) @ w / tt

        k1 = f(phi, t0)
        k2 = f(phi + h / 2 * k1, t0 + h / 2)
        k3 = f(phi + h / 2 * k2, t0 + h / 2)
        k4 = f(phi + h * k3, t0 + h)
        phi = phi + h / 6 * (k1 + 2 * k2 + 2 * k3 + k4)
        pred.append(phi.copy())
    pred = np.array(pred) * np.exp(-mu[0] * ts)[:, None]
    return {
        "t": ts,
        "log_measured": np.log(np.linalg.norm(a, axis=1)),
        "log_predicted": np.log(np.linalg.norm(pred, axis=1)),
        "mu_min": float(mu[0]),
    }
