def lorenz_field(s: np.ndarray, sigma: float, rho: float, beta: float) -> np.ndarray:
    x, y, z = s
    return np.array([sigma * (y - x), x * (rho - z) - y, x * y - beta * z])


def lorenz_jacobian(s: np.ndarray, sigma: float, rho: float, beta: float) -> np.ndarray:
    x, y, z = s
    return np.array([[-sigma, sigma, 0.0], [rho - z, -1.0, -x], [y, x, -beta]])


@dataclass
class LorenzReference:
    """Global trajectory p_ref(t) = center + L * s(t / T), s on the Lorenz attractor.

    The time scale T (km of coordinate time per Lorenz time unit) is chosen so
    that the fastest point of the reference moves at `v_max` (units of c):
    the swarm has to stay subluminal. Velocity and acceleration are evaluated
    from the Lorenz vector field itself, so feed-forward is exact rather than
    finite-differenced.
    """

    length_scale: float = 8.0  # km per Lorenz unit
    v_max: float = 0.55  # peak reference speed, units of c
    lorenz_times: float = 6.0  # duration in Lorenz time units
    sigma: float = 10.0
    rho: float = 28.0
    beta: float = 8.0 / 3.0
    burn_in: float = 20.0
    center: np.ndarray = field(default_factory=lambda: np.array([0.0, 0.0, -27.0]))

    def __post_init__(self) -> None:
        p = (self.sigma, self.rho, self.beta)
        warm = solve_ivp(
            lambda t, s: lorenz_field(s, *p), (0.0, self.burn_in), [1.0, 1.0, 1.0],
            rtol=1e-10, atol=1e-12,
        )
        self.s0 = warm.y[:, -1]
        self._sol = solve_ivp(
            lambda t, s: lorenz_field(s, *p), (0.0, self.lorenz_times), self.s0,
            rtol=1e-10, atol=1e-12, dense_output=True,
        )
        grid = np.linspace(0.0, self.lorenz_times, 4000)
        speeds = [np.linalg.norm(lorenz_field(self._sol.sol(t), *p)) for t in grid]
        # |v| = (L / T) |f(s)|  ->  T = L max|f| / v_max
        self.time_scale = self.length_scale * float(np.max(speeds)) / self.v_max

    @property
    def params(self) -> tuple[float, float, float]:
        return self.sigma, self.rho, self.beta

    @property
    def duration_km(self) -> float:
        return self.lorenz_times * self.time_scale

    def s(self, t_km: float) -> np.ndarray:
        tau = min(max(t_km / self.time_scale, 0.0), self.lorenz_times)
        return self._sol.sol(tau)

    def __call__(self, t_km: float) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
        """(position, velocity dx/dt, acceleration d2x/dt2) at coordinate time t."""
        s = self.s(t_km)
        f = lorenz_field(s, *self.params)
        jf = lorenz_jacobian(s, *self.params)
        ll, tt = self.length_scale, self.time_scale
        pos = self.center * ll + ll * s
        return pos, (ll / tt) * f, (ll / tt**2) * (jf @ f)

    def lyapunov_spectrum(self, dt: float = 1e-3) -> np.ndarray:
        """Lyapunov spectrum of the reference, per km of coordinate time.

        Standard QR (Benettin) method on the variational equations, integrated
        along the same stretch of attractor the swarm is asked to follow. The
        classic long-run values are (0.906, 0, -14.57) per Lorenz time unit;
        over a few Lorenz times the finite-time estimate is noisier.
        """
        p = self.params
        s = self.s0.copy()
        q = np.eye(3)
        acc = np.zeros(3)
        n = int(self.lorenz_times / dt)
        for _ in range(n):
            # RK4 on the joint (state, tangent) system
            def g(ss, qq):
                return lorenz_field(ss, *p), lorenz_jacobian(ss, *p) @ qq

            k1 = g(s, q)
            k2 = g(s + dt / 2 * k1[0], q + dt / 2 * k1[1])
            k3 = g(s + dt / 2 * k2[0], q + dt / 2 * k2[1])
            k4 = g(s + dt * k3[0], q + dt * k3[1])
            s = s + dt / 6 * (k1[0] + 2 * k2[0] + 2 * k3[0] + k4[0])
            q = q + dt / 6 * (k1[1] + 2 * k2[1] + 2 * k3[1] + k4[1])
            q, r = np.linalg.qr(q)
            acc += np.log(np.abs(np.diag(r)))
        return acc / (n * dt) / self.time_scale


def formation_offsets(n_robots: int, radius: float) -> np.ndarray:
    """Rigid formation offsets delta_r around the reference point, shape (R, 3).

    One robot sits on the reference; two form a pair; three a triangle; four or
    more are spread over a sphere with the Fibonacci lattice, which gives
    well-separated, non-degenerate inter-robot distances (a rigid framework).
    """
    if n_robots == 1:
        return np.zeros((1, 3))
    if n_robots <= 3:
        ang = 2 * np.pi * np.arange(n_robots) / n_robots
        return radius * np.stack([np.cos(ang), np.sin(ang), np.zeros(n_robots)], axis=1)
    k = np.arange(n_robots) + 0.5
    phi = np.arccos(1 - 2 * k / n_robots)
    theta = np.pi * (1 + 5**0.5) * k
    return radius * np.stack(
        [np.cos(theta) * np.sin(phi), np.sin(theta) * np.sin(phi), np.cos(phi)], axis=1
    )


