@dataclass
class GuidanceNetwork:
    """Each robot carries its own Lorenz oscillator s_r; the swarm synchronizes them.

    In coordinate time t (km), with T the reference time scale,

        ds_r/dt = f(s_r) / T  +  kappa_c sum_s A_rs (s_s - s_r)  +  kappa_p P_r (s_ref - s_r)

    A is the communication graph (ring by default) and P_r = 1 for the anchor
    robots that see the global trajectory s_ref directly. Robot r's slot is

        p*_r = L (s_r + c) + delta_r,   v*_r = L ds_r/dt,   a*_r = L d2s_r/dt2,

    so two robots hold their design distance exactly when their oscillators
    agree. That is where chaos enters: the Lorenz flow separates nearby states
    at lambda_max, and only the coupling pulls them back.

    Because the coupling is the identity in state space, the stability
    analysis is exact rather than approximate. Linearizing about s_ref, the
    synchronization error splits along the eigenvectors of M = kappa_c L_A +
    kappa_p P, and each mode k grows at lambda_Lorenz - mu_k. So

        network transverse exponent   = lambda_max(ref) - mu_min(M)
        robot r's conditional exponent = lambda(s_r path) - m_r,
                                         m_r = kappa_c deg_r + kappa_p P_r,

    the second being the Pecora-Carroll exponent with neighbours held fixed.
    Along the attractor the local stretching rate swings well above
    lambda_max, so a robot's local exponent turns positive in the stretching
    regions even when its average is negative. The 3D Lyapunov phase
    diagrams colour each robot's own guidance path by exactly that.
    """

    kappa_c: float = 1.0e-3  # km^-1, neighbour coupling
    kappa_p: float = 3.0e-3  # km^-1, pinning to the global trajectory
    topology: str = "ring"  # "ring" or "all"
    anchors: tuple[int, ...] | None = None  # default: robot 1 and the one opposite

    def graph(self, r: int) -> tuple[np.ndarray, np.ndarray]:
        a = np.zeros((r, r))
        if r > 1:
            if self.topology == "all":
                a = np.ones((r, r)) - np.eye(r)
            else:
                for i in range(r):
                    a[i, (i + 1) % r] = a[(i + 1) % r, i] = 1.0
        anchors = self.anchors if self.anchors is not None else tuple(sorted({0, r // 2}))
        pin = np.zeros(r)
        pin[[k for k in anchors if k < r]] = 1.0
        return a, pin

    def coupling_matrix(self, r: int) -> np.ndarray:
        a, pin = self.graph(r)
        lap = np.diag(a.sum(1)) - a
        return self.kappa_c * lap + self.kappa_p * np.diag(pin)

    def mu_min(self, r: int) -> float:
        return float(np.min(np.linalg.eigvalsh(self.coupling_matrix(r))))

    def self_gain(self, r: int) -> np.ndarray:
        """m_r: the rate at which robot r is pulled back with neighbours frozen."""
        return np.diag(self.coupling_matrix(r)).copy()

    def rates(
        self, s: np.ndarray, ref: LorenzReference, t: float
    ) -> tuple[np.ndarray, np.ndarray]:
        """(ds/dt, d2s/dt2) for all oscillators, per km and per km^2."""
        a, pin = self.graph(len(s))
        tt = ref.time_scale
        prm = ref.params
        s_ref = ref.s(t)
        sd_ref = lorenz_field(s_ref, *prm) / tt
        f = np.array([lorenz_field(x, *prm) for x in s]) / tt
        cpl = self.kappa_c * (a @ s - a.sum(1)[:, None] * s) + self.kappa_p * pin[:, None] * (
            s_ref - s
        )
        sd = f + cpl
        jac = np.array([lorenz_jacobian(x, *prm) for x in s]) / tt
        sdd = np.einsum("rij,rj->ri", jac, sd)
        sdd += self.kappa_c * (a @ sd - a.sum(1)[:, None] * sd)
        sdd += self.kappa_p * pin[:, None] * (sd_ref - sd)
        return sd, sdd


