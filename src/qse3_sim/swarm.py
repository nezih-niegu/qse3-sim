@dataclass
class FormationController:
    """Chaos-synchronization formation controller.

    Commanded coordinate acceleration of robot r (3-vectors, d2x/dt2):

        a_r = a*_r                                    feed-forward of the robot's guidance
            - omega^2 e_r - 2 zeta omega edot_r       tracking feedback
            + k_form sum_s (|p_r - p_s| - d*_rs) n_rs  distance rigidity
            + k_cons sum_s (v_s - v_r)                velocity consensus

    with e_r = p_r - p*_r and (p*, v*, a*)_r the slot produced by the robot's
    guidance oscillator. Because the feed-forward is exact, the tracking error
    obeys a linear time-invariant law whatever the guidance does, and its
    slowest eigenvalue (`contraction_rate`, from `closed_loop_matrix`) is the
    mechanical layer's conditional Lyapunov exponent.

    The command reaches the robot only through its color charge, so the
    delivered acceleration is eta_r times what the field would produce on a
    pure robot. `aware=True` gain-schedules by 1/eta_r and governs the
    engineered entangler so that min_r eta_r stays above `eta_floor`.
    `aware=False` is the same law designed for a single, unentangled robot.
    Both treat the Wong and refractive forces as unmodelled disturbances;
    `cancel_forces=True` feeds them forward from the exact reduced state,
    which is an oracle and drives the formation error to round-off.
    """

    omega: float = 0.02  # km^-1
    zeta: float = 1.0
    k_form: float = 2.0e-4  # km^-2
    k_cons: float = 2.0e-3  # km^-1
    a_max: float = 0.03  # km^-1, field-limited acceleration on a pure robot
    aware: bool = True
    cancel_forces: bool = False  # oracle feed-forward of Q_gauge + Q_top (off: honest)
    schedule_gain: bool | None = None  # 1/eta gain scheduling; None -> follows `aware`
    governor: bool | None = None  # entanglement governor; None -> follows `aware`
    eta_floor: float = 0.35
    eta_target: float = 0.6
    enabled: bool = True

    @property
    def uses_schedule(self) -> bool:
        return self.aware if self.schedule_gain is None else self.schedule_gain

    @property
    def uses_governor(self) -> bool:
        return self.aware if self.governor is None else self.governor

    def closed_loop_matrix(self, offsets: np.ndarray, eta: np.ndarray | None = None) -> np.ndarray:
        """Linearized synchronization-error dynamics, d/dt [e; edot] = A [e; edot].

        Linearized about the design formation with the guidance as the drive,
        so the chaotic feed-forward cancels exactly and what remains is the
        feedback, the rigidity springs k_form n n^T and the consensus damping.
        `eta` scales each robot's delivered acceleration (the naive controller
        on an entangled swarm); for the aware controller it is compensated.
        """
        r = len(offsets)
        eff = np.ones(r) if eta is None or self.uses_schedule else np.asarray(eta, float)
        kp = np.zeros((3 * r, 3 * r))
        kd = np.zeros((3 * r, 3 * r))
        eye = np.eye(3)
        for i in range(r):
            blk = slice(3 * i, 3 * i + 3)
            kp[blk, blk] -= self.omega**2 * eye
            kd[blk, blk] -= 2 * self.zeta * self.omega * eye
            for j in range(r):
                if i == j:
                    continue
                bj = slice(3 * j, 3 * j + 3)
                d = offsets[j] - offsets[i]
                nn = np.outer(d, d) / (d @ d)
                kp[blk, blk] -= self.k_form * nn
                kp[blk, bj] += self.k_form * nn
                kd[blk, blk] -= self.k_cons * eye
                kd[blk, bj] += self.k_cons * eye
        scale = np.repeat(eff, 3)[:, None]
        top = np.hstack([np.zeros((3 * r, 3 * r)), np.eye(3 * r)])
        return np.vstack([top, np.hstack([scale * kp, scale * kd])])

    def contraction_rate(self, offsets: np.ndarray, eta: np.ndarray | None = None) -> float:
        """Slowest decay rate of the linearized error dynamics, km^-1.

        This is the predicted conditional Lyapunov exponent (with a minus sign).
        Consensus damping pushes differential modes past critical damping, so
        adding it can slow the approach even as it smooths the formation.
        """
        ev = np.linalg.eigvals(self.closed_loop_matrix(offsets, eta))
        return float(-np.max(ev.real))

    def entangler_throttle(self, eta: np.ndarray) -> float:
        if not self.uses_governor:
            return 1.0
        lo = float(np.min(eta))
        return float(np.clip((lo - self.eta_floor) / (self.eta_target - self.eta_floor), 0, 1))

    def command(
        self,
        p: np.ndarray,
        v: np.ndarray,
        target: tuple[np.ndarray, np.ndarray, np.ndarray],
        d_star: np.ndarray,
    ) -> np.ndarray:
        """Desired coordinate acceleration for every robot, shape (R, 3).

        `target` holds each robot's own slot (p*_r, v*_r, a*_r), which the
        guidance network produces from its chaotic oscillator.
        """
        p_star, v_star, a_star = target
        e = p - p_star
        edot = v - v_star
        a = a_star - self.omega**2 * e - 2 * self.zeta * self.omega * edot
        diff = p[None, :, :] - p[:, None, :]  # p_s - p_r
        dist = np.linalg.norm(diff, axis=2)
        np.fill_diagonal(dist, 1.0)
        stretch = dist - d_star
        np.fill_diagonal(stretch, 0.0)
        a += self.k_form * np.einsum("rs,rsk->rk", stretch / dist, diff)
        a += self.k_cons * (v.sum(axis=0)[None, :] - len(v) * v)
        return a




